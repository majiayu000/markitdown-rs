"""Generate the PDF converter's data tables from the pinned pdfminer.six:
glyph names, the Latin encodings, the standard-14 font metrics, and the
predefined CMaps (packed into one binary file).

usage: uv run --project oracle python scripts/gen_pdf_data.py
"""

import gzip
import json
import os
import struct
import zlib
from pathlib import Path

import pdfminer
from pdfminer.fontmetrics import FONT_METRICS
from pdfminer.glyphlist import glyphname2unicode
from pdfminer.latin_enc import ENCODING

OUT = Path(__file__).resolve().parent.parent / "crates/markitdown-core/src/pdf"
HEADER = "// Generated by scripts/gen_pdf_data.py from pdfminer.six; do not edit.\n"


def rs(s):
    return '"' + "".join(c if c.isascii() and c.isprintable() and c not in '"\\' else f"\\u{{{ord(c):x}}}" for c in s) + '"'


def packed(items, per_line):
    lines = []
    for i in range(0, len(items), per_line):
        lines.append("    " + " ".join(items[i : i + per_line]))
    return "\n".join(lines)


def varint(v):
    assert v >= 0
    out = bytearray()
    while True:
        b = v & 0x7F
        v >>= 7
        if v:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


def zigzag(v):
    return v * 2 if v >= 0 else -v * 2 - 1


def decimal_starts():
    import unicodedata

    nd = [c for c in range(0x110000) if unicodedata.category(chr(c)) == "Nd"]
    starts = nd[::10]
    assert all(nd[i * 10 : i * 10 + 10] == list(range(s, s + 10)) for i, s in enumerate(starts))
    return starts


def num(v):
    return repr(float(v))


def main():
    glyphs = sorted(glyphname2unicode.items())
    enc = [
        f"({rs(n)}, {s or 0}, {m or 0}, {w or 0}, {p or 0}),"
        for n, s, m, w, p in ENCODING
    ]
    fonts, aliases, seen = [], [], {}
    for name, (desc, widths) in FONT_METRICS.items():
        if id(desc) in seen:
            aliases.append(f"({rs(name)}, {rs(seen[id(desc)])}),")
            continue
        seen[id(desc)] = name
        ws = sorted(widths.items())
        bbox = ", ".join(num(v) for v in desc["FontBBox"])
        fonts.append(
            f"    ({rs(name)}, Metrics {{ descent: {num(desc.get('Descent', 0))}, "
            f"bbox: [{bbox}], widths: &[\n"
            + packed([f"({rs(c)}, {w})," for c, w in ws], 16)
            + "\n    ] }),"
        )
    (OUT / "tables.rs").write_text(
        HEADER
        + "/// glyphlist.txt: glyph name to Unicode, sorted by name.\n"
        + "#[rustfmt::skip]\npub static GLYPHS: &[(&str, &str)] = &[\n"
        + packed([f"({rs(n)}, {rs(u)})," for n, u in glyphs], 9)
        + "\n];\n\n/// latin_enc: (name, standard, mac, win, pdf); 0 = not encoded.\n"
        + "#[rustfmt::skip]\npub static ENCODING: &[(&str, u8, u8, u8, u8)] = &[\n"
        + packed(enc, 4)
        + "\n];\n\n/// First code point of each run of ten Unicode decimal digits (Nd).\n"
        + "#[rustfmt::skip]\npub static DECIMAL_STARTS: &[u32] = &[\n"
        + packed([f"0x{c:x}," for c in decimal_starts()], 12)
        + "\n];\n"
    )

    (OUT / "metrics.rs").write_text(
        HEADER
        + "use super::font::Metrics;\n"
        + "\n/// Standard-14 AFM metrics and pdfminer's aliases.\n"
        + "#[rustfmt::skip]\npub static FONT_METRICS: &[(&str, Metrics)] = &[\n"
        + "\n".join(fonts)
        + "\n];\n\n/// Font names pdfminer maps onto a standard-14 font.\n"
        + "#[rustfmt::skip]\npub static FONT_ALIASES: &[(&str, &str)] = &[\n"
        + packed(aliases, 3)
        + "\n];\n"
    )

    cmap_dir = Path(pdfminer.__file__).parent / "cmap"

    def load(name):
        data = json.load(gzip.open(cmap_dir / f"{name}.json.gz", "rt", encoding="utf-8"))
        if name.startswith("to-unicode-"):
            maps = []
            for key in ("CID2UNICHR_H", "CID2UNICHR_V"):
                m = {}
                for k, v in data[key].items():
                    assert len(v) == 1 and int(k) < 65536
                    m[int(k).to_bytes(2, "big")] = ord(v)
                maps.append(m)
            return maps
        flat = {}

        def walk(d, prefix):
            for k, v in d.items():
                if isinstance(v, dict):
                    walk(v, prefix + bytes([int(k)]))
                else:
                    assert isinstance(v, int) and v < 65536
                    flat[prefix + bytes([int(k)])] = v

        walk(data.get("CODE2CID") or {}, b"")
        return flat, bool(data.get("IS_VERTICAL"))

    def runs_of(mapping):
        # (code, value) pairs as runs where the code's last byte and the
        # value both step by one, delta-encoded as varints
        out = bytearray()
        runs = []
        for code, val in sorted(mapping.items()):
            if runs:
                pc, n, pval = runs[-1]
                if len(pc) == len(code) and pc[:-1] == code[:-1] and pc[-1] + n == code[-1] and pval + n == val:
                    runs[-1][1] += 1
                    continue
            runs.append([code, 1, val])
        out += varint(len(runs))
        prev_len, prev_code, prev_val = 0, 0, 0
        for code, n, val in runs:
            value = int.from_bytes(code, "big")
            if len(code) != prev_len:
                prev_len, prev_code = len(code), 0
                out += varint(0) + bytes([len(code)])
            out += varint(value - prev_code + 1) + varint(n) + varint(zigzag(val - prev_val))
            prev_code, prev_val = value + n, val + n
        return out

    def diff(base, mapping):
        removed = sorted(k for k in base if k not in mapping)
        changed = {k: v for k, v in mapping.items() if base.get(k) != v}
        return runs_of({k: 0 for k in removed}) + runs_of(changed)

    names = sorted(f[: -len(".json.gz")] for f in os.listdir(cmap_dir) if f.endswith(".json.gz"))
    index, blob = [], bytearray()

    def add(name, kind, payload=b""):
        if payload:
            packed_entry = zlib.compress(bytes(payload), 9)
            index.append(f"({rs(name)}, {kind}{len(blob)}, {len(packed_entry)})),")
            blob.extend(packed_entry)
        else:
            index.append(f"({rs(name)}, {kind}),")

    for name in names:
        if name.startswith("to-unicode-"):
            h, v = load(name)
            add(name, "Entry::ToUnicode(", runs_of(h) + diff(h, v))
            continue
        flat, vertical = load(name)
        for enc, codec in (("UTF8", "utf-8"), ("UTF16", "utf-16-be")):
            base = name.replace(enc, "UTF32")
            if f"-{enc}-" in name and base in names:
                src, _ = load(base)
                derived = {chr(int.from_bytes(k, "big")).encode(codec, "surrogatepass"): c for k, c in src.items()}
                assert derived == flat, name
                add(name, f"Entry::Recode({rs(base)}, Recode::{enc.title()})")
                break
        else:
            hname = name[:-1] + "H"
            if name.endswith("-V") and hname in names:
                hflat, _ = load(hname)
                add(name, f"Entry::Vertical({rs(hname)}, ", diff(hflat, flat))
            else:
                add(name, "Entry::Full(", bytes([vertical]) + runs_of(flat))
    (OUT / "cmaps.bin").write_bytes(bytes(blob))
    (OUT / "cmap_index.rs").write_text(
        HEADER
        + "use super::cmap::{Entry, Recode};\n\n"
        + "/// Each predefined CMap: zlib-compressed data in cmaps.bin as\n"
        + "/// (offset, length), or how to derive it from another CMap.\n"
        + "#[rustfmt::skip]\npub static CMAPS: &[(&str, Entry)] = &[\n"
        + "\n".join("    " + e for e in index)
        + "\n];\n"
    )
    print(f"cmaps.bin: {len(blob)} bytes, {len(index)} cmaps")


main()
