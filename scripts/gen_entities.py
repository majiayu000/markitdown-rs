"""Regenerate crates/markitdown-core/src/html/entities.rs.

Tables come from the pinned CPython (html.entities.html5, html._invalid_*)
and bs4 (HTML_ENTITY_TO_CHARACTER), so lookups behave exactly as in
html.unescape() and BeautifulSoup's entity handling.

usage: uv run --project oracle python scripts/gen_entities.py
"""
import html
from html.entities import html5
from pathlib import Path

from bs4.dammit import EntitySubstitution

OUT = Path(__file__).resolve().parent.parent / "crates/markitdown-core/src/html/entities.rs"


def lit(s):
    return '"' + "".join(c if c.isascii() and c.isprintable() and c not in '"\\' else f"\\u{{{ord(c):x}}}" for c in s) + '"'


def table(name, doc, items):
    rows = [f"({lit(k)}, {lit(v)})," for k, v in sorted(items)]
    body = ["    " + " ".join(rows[i : i + 9]) for i in range(0, len(rows), 9)]
    return [f"/// {doc}", "#[rustfmt::skip]", f"pub static {name}: &[(&str, &str)] = &["] + body + ["];", ""]


lines = [
    "//! Character reference tables, generated by scripts/gen_entities.py from",
    "//! CPython 3.12 `html` and bs4 4.15. Sorted by name for binary search.",
    "",
]
lines += table("HTML5", "`html.entities.html5`: names with and without the trailing ';'.", html5.items())
lines += table("BS4", "bs4's HTML_ENTITY_TO_CHARACTER (names without ';').",
               EntitySubstitution.HTML_ENTITY_TO_CHARACTER.items())
charrefs = sorted(html._invalid_charrefs.items())
lines += ["/// `html._invalid_charrefs`", "#[rustfmt::skip]", "pub static INVALID_CHARREFS: &[(u32, &str)] = &["]
lines += ["    " + " ".join(f"({k}, {lit(v)})," for k, v in charrefs[i : i + 6]) for i in range(0, len(charrefs), 6)]
lines += ["];", ""]
cps = sorted(html._invalid_codepoints)
lines += ["/// `html._invalid_codepoints`", "#[rustfmt::skip]", "pub static INVALID_CODEPOINTS: &[u32] = &["]
lines += ["    " + " ".join(f"{c}," for c in cps[i : i + 12]) for i in range(0, len(cps), 12)]
lines += ["];", ""]
OUT.write_text("\n".join(lines))
print(f"wrote {OUT}: {len(html5)} html5, {len(EntitySubstitution.HTML_ENTITY_TO_CHARACTER)} bs4")
